import { icons } from "@phosphor-icons/core";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const sourceRoot = join(packageRoot, "src");
const outputFile = join(sourceRoot, "components/icons.tsx");
const sourceExtensions = new Set([".astro", ".mdx", ".ts", ".tsx"]);
const iconImport =
  /import\s*\{([^}]*)\}\s*from\s*["'](?:@phosphor-icons\/react(?:\/dist\/ssr)?|~\/components\/icons)["'];?/g;

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const path = join(directory, entry.name);
      if (path === outputFile) return [];
      if (entry.isDirectory()) return sourceFiles(path);
      return sourceExtensions.has(extname(entry.name)) ? [path] : [];
    }),
  );
  return nested.flat();
}

function importedNames(source) {
  const names = [];
  for (const match of source.matchAll(iconImport)) {
    for (const specifier of match[1].split(",")) {
      const imported = specifier
        .trim()
        .match(/^(?:type\s+)?([A-Za-z_$][\w$]*)/)?.[1];
      if (imported) names.push(imported);
    }
  }
  return names;
}

function resolveIcon(exportName) {
  const phosphorName = exportName.endsWith("Icon")
    ? exportName.slice(0, -"Icon".length)
    : exportName;
  const entry = icons.find(
    (candidate) =>
      candidate.pascal_name === phosphorName ||
      candidate.alias?.pascal_name === phosphorName,
  );

  if (!entry) {
    throw new Error(`No Phosphor icon metadata found for ${exportName}`);
  }

  return {
    exportName,
    componentName: `${entry.pascal_name}Svg`,
    slug: entry.name,
  };
}

const files = await sourceFiles(sourceRoot);
const names = new Set();
for (const file of files) {
  const source = await readFile(file, "utf8");
  for (const name of importedNames(source)) names.add(name);
}

const resolved = [...names]
  .map(resolveIcon)
  .sort((a, b) => a.exportName.localeCompare(b.exportName));
const canonical = [
  ...new Map(resolved.map((entry) => [entry.componentName, entry])).values(),
].sort((a, b) => a.componentName.localeCompare(b.componentName));

const imports = canonical
  .flatMap(({ componentName, slug }) => [
    `import ${componentName}Bold from "@phosphor-icons/core/bold/${slug}-bold.svg?raw";`,
    `import ${componentName}Duotone from "@phosphor-icons/core/duotone/${slug}-duotone.svg?raw";`,
    `import ${componentName}Fill from "@phosphor-icons/core/fill/${slug}-fill.svg?raw";`,
    `import ${componentName}Light from "@phosphor-icons/core/light/${slug}-light.svg?raw";`,
    `import ${componentName}Regular from "@phosphor-icons/core/regular/${slug}.svg?raw";`,
    `import ${componentName}Thin from "@phosphor-icons/core/thin/${slug}-thin.svg?raw";`,
  ])
  .join("\n");

const definitions = canonical
  .map(
    ({ componentName }) => `const ${componentName} = createIcon({
  bold: ${componentName}Bold,
  duotone: ${componentName}Duotone,
  fill: ${componentName}Fill,
  light: ${componentName}Light,
  regular: ${componentName}Regular,
  thin: ${componentName}Thin,
});`,
  )
  .join("\n\n");

const exports = resolved
  .map(
    ({ componentName, exportName }) =>
      `export const ${exportName} = ${componentName};`,
  )
  .join("\n");

const output = `/**
 * SSR-safe Solid wrappers around the official Phosphor SVG assets.
 *
 * Generated by scripts/generate-solid-icons.mjs. The adapter intentionally
 * mirrors the React package's component names so docs markup can migrate
 * without changing icon geometry, weights, or sizing.
 */
import { splitProps, type Component, type JSX } from "solid-js";

${imports}

export type IconWeight =
  | "bold"
  | "duotone"
  | "fill"
  | "light"
  | "regular"
  | "thin";

export type IconProps = Omit<
  JSX.SvgSVGAttributes<SVGSVGElement>,
  "color" | "height" | "width"
> & {
  alt?: string;
  className?: string;
  color?: string;
  mirrored?: boolean;
  size?: string | number;
  weight?: IconWeight;
};

type IconSources = Record<IconWeight, string>;

function svgBody(source: string) {
  return source.replace(/^<svg[^>]*>/, "").replace(/<\\/svg>\\s*$/, "");
}

function createIcon(sources: IconSources): Component<IconProps> {
  const bodies = Object.fromEntries(
    Object.entries(sources).map(([weight, source]) => [weight, svgBody(source)]),
  ) as Record<IconWeight, string>;

  return (inputProps) => {
    const [props, rest] = splitProps(inputProps, [
      "alt",
      "class",
      "className",
      "color",
      "mirrored",
      "size",
      "weight",
    ]);

    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={props.size ?? "1em"}
        height={props.size ?? "1em"}
        class={props.class ?? props.className}
        fill={props.color ?? "currentColor"}
        viewBox="0 0 256 256"
        aria-hidden={props.alt ? undefined : "true"}
        role={props.alt ? "img" : undefined}
        {...rest}
      >
        {props.alt ? <title>{props.alt}</title> : null}
        <g
          transform={props.mirrored ? "translate(256 0) scale(-1 1)" : undefined}
          innerHTML={bodies[props.weight ?? "regular"]}
        />
      </svg>
    );
  };
}

${definitions}

${exports}
`;

await writeFile(outputFile, output);
console.log(
  `Generated ${relative(packageRoot, outputFile)} with ${resolved.length} exports.`,
);
